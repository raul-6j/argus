const SVG_NS = "http://www.w3.org/2000/svg";

/**
 * Build an icon as a real DOM node.
 *
 * Parsed with `DOMParser` rather than assigned via `innerHTML`: the input is
 * always a hardcoded entry from the table above, but an extension that warns
 * users about injection has no business shipping an `innerHTML` write that a
 * reviewer (or `web-ext lint`) has to reason about. This route can only ever
 * produce an SVG document, never script.
 *
 * @param {string} name key of ICON_PATHS
 * @param {string} [className] optional class on the root <svg>
 * @returns {SVGElement|null} null for an unknown name
 */
export function icon(name, className) {
  const paths = ICON_PATHS[name];
  if (!paths) return null;

  const doc = new DOMParser().parseFromString(
    `<svg xmlns="${SVG_NS}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
      'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ' +
      `aria-hidden="true" focusable="false">${paths}</svg>`,
    "image/svg+xml"
  );

  const svg = doc.documentElement;
  if (svg.nodeName !== "svg") return null;
  if (className) svg.setAttribute("class", className);
  return document.importNode(svg, true);
}

/**
 * Replace every `[data-icon="name"]` in `root` with its inline glyph, inserted
 * as the element's first child. Lets the extension's HTML declare icons
 * without pasting SVG into five separate templates.
 * @param {ParentNode} [root]
 */
export function hydrateIcons(root) {
  const scope = root || document;
  for (const node of scope.querySelectorAll("[data-icon]")) {
    if (node.dataset.iconHydrated === "true") continue;
    const glyph = icon(node.dataset.icon);
    if (!glyph) continue;
    node.insertBefore(glyph, node.firstChild);
    node.dataset.iconHydrated = "true";
  }
}

